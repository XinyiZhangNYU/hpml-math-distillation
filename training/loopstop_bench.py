"""Online loop early stop in vLLM (DESIGN.md §14): the §12 rule checked during generation, off against on.

Workload: tier 2 x samples 0 and 1 = 126 requests in the order of final_eval.py (every problem for sample 0, then for
sample 1), with its chat prompt, sampling, request seeds (91432026 + 2,000,000 + item index + 100,000 * sample) and
budget 32,768, on one merged model. Engine as in sched_ext.py at 64 slots; queue mode (all requests submitted at once,
the engine driven by step()).

  off: the check runs and only records where it would have stopped and the tokens generated by then.
  on:  the first check point that fires stops the request: it is aborted (abort_request), its output is the text up to
       that point and its tokens are those generated until the abort.

Check: after every step, each request whose text passed one or more multiples of 1,000 characters is checked at each
passed point L in order with early_stop_estimate.loops(text[:L]), so the points checked are those of stop_point().

Before the engine loads: the checker check (on the saved final-run outputs of this model, items and samples, the
checker fed in chunks of 1-20 characters stops where stop_point() does) and the prediction (stop_point() on the same
saved outputs: stops and share of tokens saved), both written to OUT/prediction.json and OUT/gates.json; then the
hand-read balance gate of sched_ext.py (OUT/wait_go.json, OUT/go/cellN). After the engine loads: the loss check, the
warm-up check of §11 and the abort check (8 requests of at most 256 tokens; 0-3 aborted at 32 tokens; no output after
an abort, 4-7 finish, nothing unfinished at the end). A failed gate stops this model.

Per run, OUT/runs/NAME.json (statistics as sched_bench.run_stats plus stops, would-be stops and the exact tokens after
them) and NAME.outputs.jsonl.gz; OUT/model_summary.json compares the two runs with the prediction.

usage: python -u loopstop_bench.py --model MERGED_DIR --check-loss ADAPTER_DIR/check_loss.json --tests TESTS_DIR
       --saved FINAL/evals/cN_s1/tier2 --out DIR --cell N --order off,on
"""
import argparse
import gzip
import json
import random
import time
import traceback
from pathlib import Path

import early_stop_estimate as ese  # noqa: E402  (§12 rule)
import sched_bench as sb  # noqa: E402  (statistics, GPU monitor, counters and frozen-file check of §11)
from sched_bench import dev_eval, final_eval, sft_data  # noqa: E402

SLOTS, BUDGET, SAMPLES, TIER = 64, 32768, 2, 'tier2'
FROZEN = {**{k: v for k, v in sb.FROZEN.items() if k != 'math_dev_100.jsonl'},
          'sched_bench.py': 'b46ce2f1', 'sched_ext.py': 'a91d922b', 'early_stop_estimate.py': 'e49823d2'}
CHUNK_SEED = 20261109


class Check:
    """The §12 rule applied as text arrives; feed() returns the stop point once, when it first fires."""

    def __init__(self):
        self.text, self.next, self.stop = '', ese.CHECK_EVERY, None

    def feed(self, delta):
        self.text += delta
        while self.stop is None and self.next < len(self.text):
            L, self.next = self.next, self.next + ese.CHECK_EVERY
            if ese.loops(self.text[:L]):
                self.stop = L
                return L
        return None


def checker_check(texts):
    """The online checker, fed in random chunks, against stop_point() on every text."""
    rng, bad = random.Random(CHUNK_SEED), []
    for j, t in enumerate(texts):
        c, pos, got = Check(), 0, None
        while pos < len(t):
            n = rng.randint(1, 20)
            got = c.feed(t[pos:pos + n]) or got
            pos += n
        if got != ese.stop_point(t):
            bad.append({'index': j, 'online': got, 'offline': ese.stop_point(t)})
    return {'outputs': len(texts), 'mismatches': len(bad), 'first_mismatches': bad[:5], 'pass': not bad}


def load_saved(saved, rows, items):
    """Saved final-run outputs and scores of these items (outputs checked against summary.json)."""
    saved = Path(saved)
    summ = json.loads((saved / 'summary.json').read_text())
    assert sb.sha(saved / 'outputs.jsonl.gz') == summ['outputs_sha256'], saved
    with gzip.open(saved / 'outputs.jsonl.gz', 'rt', encoding='utf-8') as f:
        texts = {(o['id'], o['sample']): o['text'] for o in map(json.loads, f)}
    scores = {(r['id'], r['sample']): r for r in map(json.loads, (saved / 'scores.jsonl').read_text().splitlines())}
    keys = [(rows[i]['id'], s) for i, s in items]
    return [texts[k] for k in keys], [scores[k] for k in keys], summ['outputs_sha256']


def prediction(texts, scores, rows, items):
    """stop_point() on the saved outputs: stops, grade changes and the share of tokens saved (§12 token estimate)."""
    tokens = after = stops = finished = changed = 0
    for t, r, (i, _) in zip(texts, scores, items):
        L = ese.stop_point(t)
        tokens += r['output_tokens']
        if L is None:
            after += r['output_tokens']
            continue
        stops += 1
        finished += r['finish_reason'] != 'length'
        changed += final_eval.score(t[:L], rows[i]['gold'], True)['correct'] != r['correct']
        after += round(L * r['output_tokens'] / max(1, len(t)))
    return {'outputs': len(texts), 'stops': stops, 'stops_of_finished_outputs': finished, 'grade_changes': changed,
            'output_tokens': tokens, 'output_tokens_with_rule': after, 'tokens_saved_share': 1 - after / tokens,
            'truncated': sum(r['finish_reason'] == 'length' for r in scores)}


def drive(engine, prompts, params, ptok, tag, abort_if):
    """Queue mode: submits every request, steps the engine until none is live; abort_if(k, tokens, L) stops one.

    Times are seconds from the first submission; the trace is as in sched_bench.drive()."""
    from vllm.sampling_params import RequestOutputKind
    n = len(prompts)
    first, end, ntok, reason = [None] * n, [None] * n, [0] * n, [None] * n
    chk, stop_char, stop_tokens = [Check() for _ in range(n)], [None] * n, [None] * n
    trace, after_abort, last_trace, last_beat = [], 0, -1.0, 0.0
    start = time.perf_counter()
    for k in range(n):
        p = params[k].clone()
        p.output_kind = RequestOutputKind.DELTA
        engine.add_request(f'r{k:04d}.{tag}', prompts[k], p)
    live = set(range(n))
    while live:
        outs = engine.step()
        now = time.perf_counter() - start
        aborts = []
        for o in outs:
            k = int(o.request_id[1:5])
            if k not in live:
                after_abort += 1
                continue
            c = o.outputs[0]
            if c.token_ids and first[k] is None:
                first[k] = now
            ntok[k] += len(c.token_ids)
            L = chk[k].feed(c.text)
            if L is not None:
                stop_char[k], stop_tokens[k] = L, ntok[k]
            if o.finished:
                end[k], reason[k] = now, c.finish_reason
                live.discard(k)
            elif abort_if(k, ntok[k], L):
                end[k], reason[k] = now, 'loop_stop' if L is not None else 'aborted'
                live.discard(k)
                aborts.append(k)
        if aborts:
            engine.abort_request([f'r{k:04d}.{tag}' for k in aborts])
        if now - last_trace >= 1.0:
            running = [k for k in live if first[k] is not None]
            trace.append([round(now, 2), len(live), len(running), sum(ptok[k] + ntok[k] for k in running)])
            last_trace = now
        if now - last_beat >= 60:
            print('PROGRESS', tag, f'{now:.0f}s', 'finished', sum(e is not None for e in end), 'of', n,
                  'live', len(live), 'stopped', reason.count('loop_stop'), flush=True)
            last_beat = now
    wall = time.perf_counter() - start
    text = [chk[k].text[:stop_char[k]] if reason[k] == 'loop_stop' else chk[k].text for k in range(n)]
    return {'start': start, 'wall': wall, 'first': first, 'end': end, 'tokens': ntok, 'reason': reason, 'text': text,
            'generated_chars': [len(c.text) for c in chk], 'stop_char': stop_char, 'stop_tokens': stop_tokens,
            'outputs_after_abort': after_abort, 'unfinished_at_end': engine.has_unfinished_requests(),
            'trace': trace, 'groups': []}


def abort_check(engine, prompts, ptok, SamplingParams, stop):
    wp = [SamplingParams(**dev_eval.SAMPLING, max_tokens=256, seed=sb.SEED + i, **stop) for i in range(8)]
    r = drive(engine, prompts, wp, ptok, 'abortcheck', lambda k, t, L: k < 4 and t >= 32)
    ok = (r['outputs_after_abort'] == 0 and not r['unfinished_at_end'] and r['reason'][:4] == ['aborted'] * 4
          and all(x in ('stop', 'length') for x in r['reason'][4:]) and all(32 <= t < 256 for t in r['tokens'][:4]))
    return {'reasons': r['reason'], 'tokens': r['tokens'], 'outputs_after_abort': r['outputs_after_abort'],
            'unfinished_at_end': r['unfinished_at_end'], 'pass': ok}


def run_one(engine, llm, gpu, name, mode, prompts, params, ptok, items, rows, skip):
    utc, c0 = sb.now_utc(), sb.engine_counters(llm)
    res = drive(engine, prompts, params, ptok, name, (lambda k, t, L: L is not None) if mode == 'on' else
                (lambda k, t, L: False))
    c1 = sb.engine_counters(llm)
    stats, scores = sb.run_stats(res, gpu.between(res['start'], res['start'] + res['wall']), items, rows, BUDGET, 'queue')
    n = len(items)
    hit = [k for k in range(n) if res['stop_char'][k] is not None]
    graded = [k for k, (i, _) in enumerate(items) if rows[i]['id'] not in skip]
    stats.update({
        'name': name, 'mode': mode, 'slots': SLOTS, 'utc_start': utc, 'utc_end': sb.now_utc(),
        'accuracy_scored_items': sum(scores[k]['correct'] for k in graded) / len(graded), 'scored_requests': len(graded),
        'loop_stops': res['reason'].count('loop_stop'),
        'check_fired': len(hit),
        'check_fired_on_finished_output': sum(res['reason'][k] == 'stop' for k in hit),
        'check_fired_on_truncated_output': sum(res['reason'][k] == 'length' for k in hit),
        'tokens_after_check_point': sum(res['tokens'][k] - res['stop_tokens'][k] for k in hit),
        'tokens_at_check_point': {'values': sorted(res['stop_tokens'][k] for k in hit)},
        'outputs_after_abort': res['outputs_after_abort'], 'unfinished_at_end': res['unfinished_at_end'],
        'engine_counters': {x: c1[x] - c0[x] if isinstance(c1[x], (int, float)) and x in c0 else c1[x] for x in c1},
        'trace_columns': ['seconds', 'submitted_unfinished', 'running', 'resident_tokens'], 'trace': res['trace'],
        'gpu_trace_mib': [[round(t - res['start'], 1), m] for t, m in gpu.samples
                          if res['start'] <= t <= res['start'] + res['wall']]})
    if mode == 'off':  # what the check would have done to these same outputs
        stats['would_change_grade'] = sum(final_eval.score(res['text'][k][:res['stop_char'][k]], rows[items[k][0]]['gold'],
                                                           True)['correct'] != scores[k]['correct'] for k in hit)
        stats['exact_tokens_saved_share'] = stats['tokens_after_check_point'] / stats['output_tokens']
    recs = [{'k': k, 'id': rows[i]['id'], 'sample': s, 'seed': seed, 'scored': rows[i]['id'] not in skip,
             'prompt_tokens': ptok[k], 'output_tokens': res['tokens'][k], 'finish_reason': res['reason'][k],
             'first_token_s': res['first'][k], 'finish_s': res['end'][k], 'stop_char': res['stop_char'][k],
             'stop_tokens': res['stop_tokens'][k], 'generated_chars': res['generated_chars'][k],
             'correct': scores[k]['correct'], 'think_closed': scores[k]['think_closed'], 'text': res['text'][k]}
            for k, ((i, s), seed) in enumerate(zip(items, [p.seed for p in params]))]
    return stats, recs


def run(a):
    import importlib.metadata as metadata
    out = Path(a.out)
    (out / 'runs').mkdir(parents=True, exist_ok=True)
    modes = a.order.split(',')
    assert sorted(modes) == ['off', 'on'], modes
    names = [f'{Path(a.out).name}_{m}' for m in modes]
    if (out / 'model_summary.json').exists():
        print('MODEL_DONE_ALREADY', a.out, flush=True)
        return
    shas = {n: sb.sha(sb.HERE / n) for n in FROZEN}
    assert all(shas[n].startswith(FROZEN[n]) for n in FROZEN), shas
    sb.GROUP = SLOTS  # run_stats() reads the slot count from here
    rows = final_eval.load_tier(a.tests, TIER)
    skip = final_eval.excluded_ids(a.tests)
    number = final_eval.TIERS[TIER][0]
    items = [(i, s) for s in range(SAMPLES) for i in range(len(rows))]
    saved_texts, saved_scores, saved_sha = load_saved(a.saved, rows, items)
    gates_p = out / 'gates.json'
    gates = json.loads(gates_p.read_text()) if gates_p.exists() else {}
    gates['checker'] = checker_check(saved_texts)
    pred = {'utc': sb.now_utc(), 'saved': a.saved, 'saved_outputs_sha256': saved_sha,
            **prediction(saved_texts, saved_scores, rows, items)}
    dev_eval.save(out / 'prediction.json', pred)
    dev_eval.save(gates_p, gates)
    print('PREDICTION', json.dumps(pred), flush=True)
    print('GATE_CHECKER', json.dumps(gates['checker']), flush=True)
    assert gates['checker']['pass'], 'The online checker does not match stop_point().'
    import sched_ext
    if not sched_ext.gate(out.parent, a.cell):
        dev_eval.save(out / 'not_run.json', {'utc': sb.now_utc(), 'reason': 'balance gate answered stop'})
        print('NOT_RUN', a.out, flush=True)
        return
    import torch
    from vllm import LLM, SamplingParams
    tok = sft_data.load_tokenizer()
    stop = dict(stop_token_ids=[tok.convert_tokens_to_ids('<|im_end|>'), tok.convert_tokens_to_ids('<|endoftext|>')])
    prompts = [sft_data.chat_prompt(rows[i]['problem']) for i, _ in items]
    ptok = [len(tok.encode(p, add_special_tokens=False)) for p in prompts]
    meta = {'utc_start': sb.now_utc(), 'model': a.model, 'slots': SLOTS, 'max_model_len': sb.MAX_MODEL_LEN,
            'engine': dev_eval.ENGINE, 'sampling': dev_eval.SAMPLING, 'budget': BUDGET, 'tier': TIER,
            'samples': SAMPLES, 'requests': len(items), 'order': modes, 'stop': stop,
            'seed_rule': '91432026 + 1000000*tier + item index + 100000*sample', 'frozen_sha256': shas,
            'script_sha256': sb.sha(Path(__file__)), 'gpu': torch.cuda.get_device_name(0),
            'loop_rule': {'check_every_chars': ese.CHECK_EVERY, 'probe_chars': ese.PROBE,
                          'max_period_chars': ese.MAX_P, 'min_loop_chars': ese.MIN_LOOP},
            'versions': {n: metadata.version(n) for n in ['torch', 'transformers', 'vllm', 'math-verify']}}
    merge = Path(a.model) / 'merge_report.json'
    meta['merge_report'] = json.loads(merge.read_text()) if merge.exists() else None
    t = time.perf_counter()
    llm = LLM(model=a.model, dtype='bfloat16', max_model_len=sb.MAX_MODEL_LEN, max_num_seqs=SLOTS, **dev_eval.ENGINE,
              enforce_eager=False, enable_prefix_caching=False, language_model_only=True, seed=sb.SEED,
              disable_log_stats=False)
    meta['load_seconds'] = time.perf_counter() - t
    engine = llm.llm_engine
    try:
        cc = engine.vllm_config.cache_config
        meta['kv_cache'] = {'num_gpu_blocks': cc.num_gpu_blocks, 'block_size': cc.block_size}
    except Exception as e:  # noqa: BLE001  (informational only)
        meta['kv_cache'] = repr(e)
    dev_eval.save(out / 'engine.json', meta)
    gates['check_loss'] = dev_eval.check_nll(llm, json.loads(Path(a.check_loss).read_text()))
    dev_eval.save(gates_p, gates)
    print('CHECK_LOSS', json.dumps({k: gates['check_loss'][k] for k in ('max_relative_difference', 'pass')}), flush=True)
    assert gates['check_loss']['pass'], 'The merged weights do not reproduce the adapter loss.'
    wp = [SamplingParams(**dev_eval.SAMPLING, max_tokens=256, seed=sb.SEED + i, **stop) for i in range(8)]
    w = sb.drive(engine, prompts[:8], wp, ptok, 0, 'warmup')
    g = llm.generate(prompts[:8], [p.clone() for p in wp], use_tqdm=False)
    gates['warmup'] = {'step_loop_tokens': w['tokens'], 'generate_tokens': [len(x.outputs[0].token_ids) for x in g],
                       'identical_text': sum(x == y.outputs[0].text for x, y in zip(w['text'], g)),
                       'pass': all(e is not None for e in w['end']) and all(0 < x <= 256 for x in w['tokens'])}
    dev_eval.save(gates_p, gates)
    print('WARMUP', json.dumps(gates['warmup']), flush=True)
    assert gates['warmup']['pass'], 'step loop check failed'
    gates['abort'] = abort_check(engine, prompts[:8], ptok, SamplingParams, stop)
    dev_eval.save(gates_p, gates)
    print('GATE_ABORT', json.dumps(gates['abort']), flush=True)
    assert gates['abort']['pass'], 'abort check failed'
    gpu = sb.GpuMonitor()
    gpu.start()
    seed = lambda i, s: sb.SEED + 1000000 * number + i + 100000 * s  # noqa: E731  (final_eval.py)
    for name, mode in zip(names, modes):
        p = out / 'runs' / f'{name}.json'
        if p.exists() and json.loads(p.read_text()).get('complete'):
            print('RUN_SKIP_DONE', name, flush=True)
            continue
        params = [SamplingParams(**dev_eval.SAMPLING, max_tokens=BUDGET, seed=seed(i, s), **stop) for i, s in items]
        print('RUN_START', name, sb.now_utc(), flush=True)
        stats, recs = run_one(engine, llm, gpu, name, mode, prompts, params, ptok, items, rows, skip)
        with gzip.open(out / 'runs' / f'{name}.outputs.jsonl.gz', 'wt', encoding='utf-8') as f:
            f.writelines(json.dumps(r, ensure_ascii=False) + '\n' for r in recs)
        stats['outputs_sha256'] = sb.sha(out / 'runs' / f'{name}.outputs.jsonl.gz')
        stats['complete'] = True
        dev_eval.save(p, stats)
        print('RUN_END', name, json.dumps({x: stats[x] for x in ('generation_wall_seconds', 'output_tokens',
                                                                  'output_tokens_per_second', 'loop_stops',
                                                                  'check_fired', 'truncated', 'accuracy')}), flush=True)
    gpu.stop.set()
    runs, texts = {}, {}
    for name, mode in zip(names, modes):
        runs[mode] = json.loads((out / 'runs' / f'{name}.json').read_text())
        with gzip.open(out / 'runs' / f'{name}.outputs.jsonl.gz', 'rt', encoding='utf-8') as f:
            texts[mode] = [json.loads(x) for x in f]
    off, on = runs['off'], runs['on']
    not_stopped = [k for k, r in enumerate(texts['on']) if r['finish_reason'] != 'loop_stop']
    keys = ('generation_wall_seconds', 'output_tokens', 'output_tokens_per_second', 'busy_slot_share', 'finish_seconds',
            'truncated', 'loop_stops', 'check_fired', 'check_fired_on_finished_output', 'accuracy',
            'accuracy_scored_items', 'peak_resident_tokens', 'engine_counters')
    summary = {'utc': sb.now_utc(), 'model': a.model, 'requests': len(items), 'prediction': pred,
               'on_over_off': {'output_tokens': on['output_tokens'] / off['output_tokens'],
                               'generation_wall_seconds': on['generation_wall_seconds'] / off['generation_wall_seconds'],
                               'output_tokens_per_second': on['output_tokens_per_second'] / off['output_tokens_per_second']},
               'tokens_saved_share_measured': 1 - on['output_tokens'] / off['output_tokens'],
               'tokens_saved_share_exact_on_off_outputs': off['exact_tokens_saved_share'],
               'off_would_change_grade': off['would_change_grade'],
               'identical_outputs': {
                   'off_on_among_not_stopped': sum(texts['off'][k]['text'] == texts['on'][k]['text'] for k in not_stopped)
                   / max(1, len(not_stopped)),
                   'off_saved': sum(r['text'] == t for r, t in zip(texts['off'], saved_texts)) / len(items)},
               'runs': {m: {x: r[x] for x in keys} for m, r in runs.items()}}
    dev_eval.save(out / 'model_summary.json', summary)
    print('MODEL_DONE', a.out, json.dumps({k: summary[k] for k in ('on_over_off', 'tokens_saved_share_measured',
                                                                   'tokens_saved_share_exact_on_off_outputs')}),
          flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    for x in ('--model', '--check-loss', '--tests', '--saved', '--out', '--order'):
        ap.add_argument(x, required=True)
    ap.add_argument('--cell', type=int, required=True)
    args = ap.parse_args()
    try:
        run(args)
    except Exception:
        Path(args.out).mkdir(parents=True, exist_ok=True)
        (Path(args.out) / 'error.json').write_text(json.dumps({'traceback': traceback.format_exc()}, indent=2))
        raise
