"""Heavy cleaning (group 4) with Claude as the annotator. Free and offline: no API.

Usage (run with python -I; WORK_DIR is outside this directory):
  python -I claude_label.py examples OUT.md
      human5 hand labels shown per heavy_clean_v3.split_units unit, read before labelling (LABELING_GUIDE.md §5).
  python -I claude_label.py prepare INPUTS.jsonl WORK_DIR [BATCH_SIZE] [SEED]
      Rows with at least MIN_TOKENS reasoning tokens are shuffled (seeded) into batches. Each batch gets one heldout5
      trace as a calibration item at a seeded position, under opaque keys t01, t02, ... Writes batches/batch_NNN.md
      (what the labeller reads), batches/batch_NNN_key.json (key -> id; not read while labelling) and prepare.json.
  python -I claude_label.py apply WORK_DIR NNN
      Reads labels/batch_NNN.json, checks it strictly, deletes with heavy_clean_v3.apply_plan, scores the calibration
      item against its reference labels and writes results/batch_NNN_{cleaned.jsonl,report.json,diff.html}.
      Exit code 1 if the labels break a rule; exit code 2 if they are valid but the calibration gate fails.

Unlike the DeepSeek pipeline, an item that apply_plan would drop or trim is an error here: the labeller fixes it.
INPUTS rows need id, problem, text, reasoning_content, reasoning_tokens (and set, level for the diff page).
"""
import hashlib
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PILOT = HERE.parent / 'heavy_clean_pilot'
GUIDE = HERE / 'LABELING_GUIDE.md'
MIN_TOKENS = 300  # shorter traces are not annotated
BATCH_SIZE = 10
SEED = 20261019
KINDS = {'abandoned': {'branch'}, 'repeat': {'reverify', 'reread', 'tail'}}
GATE = {'precision': 0.70, 'f1': 0.60}  # same as the pilot's suggested standard
REQUIRED = ('id', 'problem', 'text', 'reasoning_content', 'reasoning_tokens')


def sha_bytes(b):
    return hashlib.sha256(b).hexdigest()


def sha(p):
    return sha_bytes(Path(p).read_bytes())


def load_pilot():
    sys.path.insert(0, str(PILOT))
    import heavy_clean_v3 as hc
    rows = [json.loads(x) for x in (PILOT / 'heavy_pilot_inputs_r3.jsonl').read_text(encoding='utf-8').splitlines() if x.strip()]
    ann = json.loads((PILOT / 'human_annotations_r3.json').read_text(encoding='utf-8'))['traces']
    return hc, rows, ann


def read_jsonl(p):
    return [json.loads(x) for x in Path(p).read_text(encoding='utf-8').splitlines() if x.strip()]


def unit_lines(hc, text):
    return [(i, ' '.join(text[s:e].split())) for i, (s, e) in enumerate(hc.split_units(text))]


def examples(out):
    """human5 labels snapped to units (their boundaries fall on unit boundaries), grouped into runs."""
    hc, rows, ann = load_pilot()
    parts = ['# human5 labels per unit (read before labelling)\n\nGenerated by `claude_label.py examples` from '
             '`human_annotations_r3.json`. Deleted: abandoned, repeat. Kept: main, check (first check), plan/meta. '
             'The heldout5 calibration traces are not shown here.\n']
    for r in rows:
        if r['set'] != 'human5':
            continue
        text, segs = r['reasoning_content'], ann[r['id']]
        units = hc.split_units(text)
        labs = []
        for s, e in units:
            best = max(segs, key=lambda g: min(e, g['end']) - max(s, g['start']))
            assert best['start'] <= s and e <= best['end'], (r['id'], s, e)  # unit lies inside one segment
            labs.append(best['label'])
        parts.append(f'\n## {r["id"]} (level {r["level"]}, {r["reasoning_tokens"]} reasoning tokens, '
                     f'{len(units)} units)\n\n**Problem:** {" ".join(r["problem"].split())}\n')
        i = 0
        while i < len(units):
            j = i
            while j + 1 < len(units) and labs[j + 1] == labs[i]:
                j += 1
            mark = 'delete' if labs[i] in hc.HUMAN_DELETE else 'keep'
            body = ' '.join(f'[{k}] ' + ' '.join(text[units[k][0]:units[k][1]].split()) for k in range(i, j + 1))
            parts.append(f'\n- **[{i}–{j}] {mark} / {labs[i]}**: {body}\n')
            i = j + 1
    Path(out).write_text(''.join(parts), encoding='utf-8')
    print('wrote', out, 'sha256', sha(out))


def prepare(inputs, work, batch_size=BATCH_SIZE, seed=SEED):
    hc, pilot_rows, _ = load_pilot()
    work = Path(work)
    assert not (work / 'prepare.json').exists(), 'already prepared: never reshuffle labelled batches'
    rows = read_jsonl(inputs)
    assert len({r['id'] for r in rows}) == len(rows), 'duplicate ids'
    for r in rows:
        assert all(k in r for k in REQUIRED), r.get('id')
    todo = sorted((r for r in rows if r['reasoning_tokens'] >= MIN_TOKENS), key=lambda r: r['id'])
    short = sorted(r['id'] for r in rows if r['reasoning_tokens'] < MIN_TOKENS)
    rng = random.Random(seed)
    rng.shuffle(todo)
    calib = [r for r in pilot_rows if r['set'] == 'heldout5']
    (work / 'batches').mkdir(parents=True)
    (work / 'labels').mkdir()
    (work / 'results').mkdir()
    batches = [todo[i:i + batch_size] for i in range(0, len(todo), batch_size)]
    for n, items in enumerate(batches, 1):
        cal = dict(calib[(n - 1) % len(calib)], calibration=True)
        items = list(items)
        items.insert(rng.randrange(len(items) + 1), cal)
        keys = {f't{k:02d}': r for k, r in enumerate(items, 1)}
        md = [f'# batch {n:03d}: {len(items)} traces\n\nLabel per `LABELING_GUIDE.md` and write `labels/batch_{n:03d}.json`.\n']
        for key, r in keys.items():
            lines = unit_lines(hc, r['reasoning_content'])
            md.append(f'\n## {key} ({len(lines)} units, numbered 0–{len(lines) - 1})\n\n### Problem\n\n{r["problem"]}\n\n'
                      f'### Final solution (shown to the user after the reasoning)\n\n{r["text"]}\n\n### Reasoning units\n\n'
                      + '\n'.join(f'[{i}] {t}' for i, t in lines) + '\n')
        (work / 'batches' / f'batch_{n:03d}.md').write_text(''.join(md), encoding='utf-8')
        key_doc = {k: {'id': r['id'], 'calibration': bool(r.get('calibration')),
                       'reasoning_sha256': sha_bytes(r['reasoning_content'].encode('utf-8'))} for k, r in keys.items()}
        (work / 'batches' / f'batch_{n:03d}_key.json').write_text(json.dumps(key_doc, indent=1), encoding='utf-8')
    doc = {'inputs': str(inputs), 'inputs_sha256': sha(inputs), 'n_rows': len(rows), 'n_annotated': len(todo),
           'n_short_kept_light': len(short), 'short_ids': short, 'min_tokens': MIN_TOKENS, 'batch_size': batch_size,
           'seed': seed, 'n_batches': len(batches), 'guide_sha256': sha(GUIDE), 'tool_sha256': sha(__file__)}
    (work / 'prepare.json').write_text(json.dumps(doc, indent=1), encoding='utf-8')
    print('prepared', len(batches), 'batches;', len(todo), 'to label;', len(short), 'short traces kept light')


def check_item(key, lab):
    """Strict schema check of one trace's labels; returns error strings."""
    errs = []
    if not isinstance(lab, dict) or set(lab) - {'main_derivation', 'delete'}:
        return [f'{key}: labels must be an object with main_derivation and delete only']
    for d in lab.get('delete', []):
        kinds = KINDS.get(d.get('label'))
        if kinds is None or d.get('kind') not in kinds:
            errs.append(f'{key}: bad label/kind {d.get("label")}/{d.get("kind")} at {d.get("first")}')
        need = 'dropped_at' if d.get('label') == 'abandoned' else 'same_as'
        if need not in d:
            errs.append(f'{key}: {d.get("label")} at {d.get("first")} lacks {need}')
        if not str(d.get('why', '')).strip():
            errs.append(f'{key}: item at {d.get("first")} lacks why')
    return errs


def apply(work, n):
    hc, pilot_rows, ann = load_pilot()
    work = Path(work)
    prep = json.loads((work / 'prepare.json').read_text(encoding='utf-8'))
    assert sha(prep['inputs']) == prep['inputs_sha256'], 'inputs changed since prepare'
    tag = f'batch_{int(n):03d}'
    keys = json.loads((work / 'batches' / f'{tag}_key.json').read_text(encoding='utf-8'))
    lab_path = work / 'labels' / f'{tag}.json'
    labels = json.loads(lab_path.read_text(encoding='utf-8'))
    by_id = {r['id']: r for r in read_jsonl(prep['inputs'])}
    pilot = {r['id']: r for r in pilot_rows}
    errs = []
    if labels.get('guide_sha256') != prep['guide_sha256']:
        errs.append('guide_sha256 does not match the guide recorded in prepare.json')
    if set(labels.get('labels', {})) != set(keys):
        errs.append(f'labelled keys differ from the batch: missing {sorted(set(keys) - set(labels.get("labels", {})))}, '
                    f'extra {sorted(set(labels.get("labels", {})) - set(keys))}')
    results, calib = [], None
    for key, meta in keys.items():
        row = pilot[meta['id']] if meta['calibration'] else by_id[meta['id']]
        text = row['reasoning_content']
        assert sha_bytes(text.encode('utf-8')) == meta['reasoning_sha256'], key
        units = hc.split_units(text)
        lab = labels.get('labels', {}).get(key)
        if lab is None:
            continue
        e = check_item(key, lab)
        try:
            plan = hc.parse_response(json.dumps(lab), len(units))
        except ValueError as ex:
            errs.append(f'{key}: {ex}')
            continue
        for d in plan['delete']:
            for f in ('same_as_error', 'dropped_at_error'):
                if f in d:
                    e.append(f'{key}: {d[f]}')
        kinds = {(d['first'], d['last']): d.get('kind') for d in lab.get('delete', [])}
        for d in plan['delete']:
            d['kind'] = kinds.get((d['first'], d['last']))
        res = hc.apply_plan(text, units, plan)
        e += [f'{key}: item {d["first"]}-{d["last"]} refused: {d["reason"]}' for d in res['dropped']]
        e += [f'{key}: item {d["first"]}-{d["last"]} overlaps main_derivation' for d in res['trimmed']]
        errs += e
        assert hc.is_subsequence(res['cleaned_reasoning'], text), key
        out = {'id': row['id'], 'key': key, 'calibration': meta['calibration'], 'set': row.get('set', ''),
               'n_units': len(units), 'plan': plan, 'text': row['text'], **res,
               'deleted_tokens_est': round(res['delete_share_chars'] * row['reasoning_tokens'])}
        if meta['calibration']:
            out['agreement'] = hc.agreement(text, units, res['deleted_spans'], ann[row['id']])
            calib = out
        results.append(out)
    if errs:
        print('LABEL ERRORS (fix labels/' + tag + '.json and rerun):')
        print('\n'.join(errs))
        sys.exit(1)
    m = calib['agreement']['model']
    passed = all(m[k] is not None and m[k] >= v for k, v in GATE.items())
    report = {'batch': tag, 'labels_sha256': sha(lab_path), 'guide_sha256': prep['guide_sha256'], 'tool_sha256': sha(__file__),
              'inputs_sha256': prep['inputs_sha256'],
              'calibration': {'id': calib['id'], 'key': calib['key'], **{k: m[k] for k in ('precision', 'recall', 'f1',
                              'pred_share', 'human_share')}, 'gate': GATE, 'passed': passed},
              'by_status': {s: sum(r['status'] == s for r in results if not r['calibration'])
                            for s in sorted({r['status'] for r in results if not r['calibration']})},
              'traces': {r['id']: {k: r[k] for k in ('key', 'status', 'delete_share_chars', 'deleted_tokens_est')}
                         for r in results if not r['calibration']}}
    res_dir = work / 'results'
    (res_dir / f'{tag}_cleaned.jsonl').write_text(''.join(json.dumps(r, ensure_ascii=False) + '\n'
                                                          for r in results if not r['calibration']), encoding='utf-8')
    (res_dir / f'{tag}_report.json').write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding='utf-8')
    rows = [dict(pilot[r['id']] if r['calibration'] else by_id[r['id']], set='calibration' if r['calibration'] else 'labelled')
            for r in results]
    for r in rows:
        r.setdefault('level', '?')
    page = hc.render_html(rows, results, {calib['id']: ann[calib['id']]}, {})
    page = page.replace('Heavy cleaning: what the annotator deletes', f'Heavy cleaning, Claude labels, {tag}')
    page = page.replace('<title>Heavy cleaning</title>', f'<title>Heavy cleaning {tag}</title>')
    (res_dir / f'{tag}_diff.html').write_text(page, encoding='utf-8')
    print(json.dumps(report['calibration']), json.dumps(report['by_status']))
    if not passed:
        print('CALIBRATION GATE FAILED: stop and review the differences; do not relabel the calibration item.')
        sys.exit(2)


if __name__ == '__main__':
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8')
    cmd, args = sys.argv[1], sys.argv[2:]
    if cmd == 'examples':
        examples(*args)
    elif cmd == 'prepare':
        prepare(args[0], args[1], *(int(a) for a in args[2:]))
    elif cmd == 'apply':
        apply(*args)
    else:
        sys.exit(__doc__)
